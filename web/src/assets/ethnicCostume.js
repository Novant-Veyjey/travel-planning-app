export const DEFAULT_COSTUME = COSTUMES.han;

/**
 * 把后端的"民族"标签解析成服饰参数
 * @param {string} 民族 如"藏族" / "苗族/侗族" / "汉族（客家）/畲族"
 * @returns {Object} 服饰参数（含 key / 民族 / 服饰 / 配色 / 款式 / 头饰 / 图案）
 */
export function resolveCostume(民族) {
  const text = String(民族 || "");
  let best = null;
  for (const [re, key] of RULES) {
    const m = text.match(re);
    if (!m) continue;
    const idx = m.index ?? 0;
    if (!best || idx < best.idx) best = { key, idx };
  }
  const key = best ? best.key : "han";
  return { key, ...(COSTUMES[key] || DEFAULT_COSTUME) };
}

