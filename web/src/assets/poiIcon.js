// 兜底徽章：专属配色 + 专属形状，由名称哈希稳定决定（同名恒等，异名大概率不同）
const BADGE_COLORS = [
  "#ef8a9b", "#f2a65a", "#e8c547", "#7fc48a", "#5fb3c4",
  "#7d9bea", "#a988e0", "#d98ec4", "#8fbf7a", "#e0975f",
];
const BADGE_SHAPES = ["circle", "triangle", "square", "diamond", "hexagon", "star", "drop", "wave"];

function hashOf(text) {
  let h = 5381;
  for (const ch of String(text || "")) h = (h * 33 + ch.codePointAt(0)) % 1000003;
  return h;
}

/** 单个名称的候选图案（语义候选 + 兜底徽章） */
function candidatesOf(name, type) {
  const n = String(name || "").trim();
  const t = String(type || "").trim();
  // 名称与类型分开测试：避免拼接后 "塔$" 这类锚点规则永远匹配不上
  for (const [re, list] of RULES) {
    if (re.test(n) || (t && re.test(t))) {
      // 按优先级原序返回：首选一定是最贴切的图案，
      // 同组撞车时再由 assignIcons 顺延到下一个同义图案
      return [...list];
    }
  }
  return [];
}

/** 兜底徽章：名称首字 + 专属色 + 专属形状 */
function badgeOf(name) {
  const h = hashOf(name);
  const char = String(name || "?").trim().charAt(0) || "?";
  return {
    kind: "badge",
    char,
    bg: BADGE_COLORS[h % BADGE_COLORS.length],
    shape: BADGE_SHAPES[(h >> 3) % BADGE_SHAPES.length],
    key: `badge:${char}:${h % 997}`,
  };
}

/**
 * 为一组打卡点分配互不重复的图标
 * @param {{名称:string, 类型?:string}[]} list
 * @returns {{kind:string, emoji?:string, char?:string, bg:string, shape?:string}[]}
 */
export function assignIcons(list = []) {
  const used = new Set();
  return list.map((poi) => {
    const name = poi?.名称 || "";
    const emojis = candidatesOf(name, poi?.类型);
    for (const e of emojis) {
      if (!used.has(e)) {
        used.add(e);
        return { kind: "emoji", emoji: e, bg: "#f4f7fb" };
      }
    }
    // 语义图案用尽（或压根没命中）→ 生成唯一徽章
    let badge = badgeOf(name);
    let guard = 0;
    while (used.has(badge.key) && guard++ < BADGE_SHAPES.length * 2) {
      badge = badgeOf(`${name}#${guard}`);
    }
    used.add(badge.key);
    return badge;
  });
}

/** 单个图标（列表场景请用 assignIcons 以保证组内不重复） */
export function iconOf(name, type = "") {
  const emojis = candidatesOf(name, type);
  if (emojis.length) return { kind: "emoji", emoji: emojis[0], bg: "#f4f7fb" };
  return badgeOf(name);
}
