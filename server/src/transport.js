// 默认兜底（未匹配时的粗略估算）
const DEFAULT = { 高铁: 6, 飞机: 2, 自驾: 16 };

/** 获取两地全程交通耗时（小时） */
export function getTransportHours(from, to) {
  if (!from || !to) return DEFAULT;
  const k1 = `${from}|${to}`;
  const k2 = `${to}|${from}`;
  return TRANSPORT_TABLE[k1] || TRANSPORT_TABLE[k2] || DEFAULT;
}

/** 格式化小时数 → "约 X 小时 Y 分钟" / "约 X 小时" / "约 Y 分钟" */
function fmtHours(h) {
  if (h == null || isNaN(h)) return "约需数小时";
  if (h < 1) return `约 ${Math.round(h * 60)} 分钟`;
  const hh = Math.floor(h);
  const mm = Math.round((h - hh) * 60);
  if (mm === 0) return `约 ${hh} 小时`;
  return `约 ${hh} 小时 ${mm} 分钟`;
}

/** 返回 3 种交通方式（高铁/飞机/自驾）的耗时文本和图标 */
export function getTransportOptions(from, to) {
  const t = getTransportHours(from, to);
  return [
    { 方式: "高铁", 耗时: fmtHours(t.高铁), ico: "🚄" },
    { 方式: "飞机", 耗时: fmtHours(t.飞机), ico: "✈️" },
    { 方式: "自驾", 耗时: fmtHours(t.自驾), ico: "🚗" },
  ];
}

export default getTransportOptions;