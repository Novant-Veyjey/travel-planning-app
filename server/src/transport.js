function getCoord(city) {
  return CITY_COORDS[city] || null;
}

function haversine([lat1, lon1], [lat2, lon2]) {
  const R = 6371;
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLon = (lon2 - lon1) * Math.PI / 180;
  const a = Math.sin(dLat / 2) ** 2 +
            Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) *
            Math.sin(dLon / 2) ** 2;
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

// 根据直线距离估算耗时（公里）
function estimateByDistance(distanceKm) {
  // 高铁：平均旅速约 220 km/h（含停站）；自驾：约 90 km/h；飞机：飞行+机场往返
  const 高铁 = Math.max(0.8, +(distanceKm / 220 * 1.15).toFixed(1)); // 1.15 为停站系数
  const 自驾 = Math.max(1.0, +(distanceKm / 90).toFixed(1));
  let 飞机 = null;
  if (distanceKm > 500) {
    飞机 = +(1.5 + distanceKm / 800).toFixed(1);
  }
  return { 高铁, 飞机, 自驾 };
}

function getTransportTimes(from, to) {
  const key = `${from}-${to}`;
  if (TRANSPORT_TABLE[key]) return TRANSPORT_TABLE[key];

  // 未命中：用经纬度距离估算
  const c1 = getCoord(from);
  const c2 = getCoord(to);
  if (c1 && c2) {
    const d = haversine(c1, c2);
    return estimateByDistance(d);
  }

  // 连坐标都没有的兜底：给一个偏保守的估算
  return { 高铁: 4.0, 飞机: 2.5, 自驾: 10.0 };
}

function getTransportOptions(from, to) {
  const times = getTransportTimes(from, to);

  const icoMap = { 高铁: '🚄', 飞机: '✈️', 自驾: '🚗' };

  // 构建选项并过滤掉不存在的交通方式
  let options = Object.entries(times)
    .filter(([mode, hours]) => hours !== null && hours !== undefined)
    .map(([mode, hours]) => ({ 方式: mode, 耗时: `约 ${hours} 小时`, hours, ico: icoMap[mode] }));

  // 规则过滤
  const 高铁项 = options.find(o => o.方式 === '高铁');
  const 高铁小时 = 高铁项 ? 高铁项.hours : 99;

  options = options.filter(o => {
    if (o.方式 === '飞机') {
      // 高铁 2.5 小时内到达，飞机无意义；飞机不比高铁快也不推
      if (高铁小时 <= 2.5) return false;
      if (o.hours >= 高铁小时) return false;
    }
    if (o.方式 === '自驾') {
      // 超过 1000 km 自驾太累，不推荐展示
      if (o.hours >= 12) return false;
    }
    return true;
  });

  // 排序：综合耗时短的优先；飞机若只比高铁省 0.5h 以内，高铁更优
  options.sort((a, b) => {
    const aScore = a.方式 === '飞机' ? a.hours + 0.8 : a.hours;
    const bScore = b.方式 === '飞机' ? b.hours + 0.8 : b.hours;
    return aScore - bScore;
  });

  // 兜底：若过滤后为空，至少保留高铁
  if (options.length === 0 && times.高铁) {
    options.push({ 方式: '高铁', 耗时: `约 ${times.高铁} 小时`, hours: times.高铁, ico: icoMap['高铁'] });
  }

  return options;
}

