const DEFAULT_HEIGHT = 40;

function haversine(lat1, lon1, lat2, lon2) {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

/** 城市建筑（真实坐标 + 高度），供 3D 立体渲染 */
export function getCityBuildings(city) {
  const out = [];
  for (const key of Object.keys(POI_COORDS)) {
    if (!key.startsWith(`${city}|`)) continue;
    const name = key.split("|")[1];
    const [lat, lon] = POI_COORDS[key];
    out.push({
      名称: name,
      纬度: lat,
      经度: lon,
      高度: BUILDING_HEIGHT[name] || DEFAULT_HEIGHT,
    });
  }
  return out.sort((a, b) => b.高度 - a.高度);
}

/** 根据城市名取地理数据（未收录的城市仅返回建筑） */
export function getCityGeo(city) {
  const g = CITY_GEO[city];
  return {
    城市: city,
    中心: g?.中心 || null,
    水系: g?.水系 || [],
    道路: g?.道路 || [],
    建筑: getCityBuildings(city),
  };
}

/**
 * 周边推荐：给定真实经纬度，按真实距离返回半径内景点与步行耗时
 * @param {string} city 城市
 * @param {number} lat 当前纬度
 * @param {number} lon 当前经度
 * @param {number} radiusKm 搜索半径（公里）
 */
export function getNearby(city, lat, lon, radiusKm = 1.5, limit = 8) {
  const list = [];
  const seen = new Set();
  for (const key of Object.keys(POI_COORDS)) {
    if (!key.startsWith(`${city}|`)) continue;
    const name = key.split("|")[1];
    if (seen.has(name)) continue;
    seen.add(name);
    const [plat, plon] = POI_COORDS[key];
    const distKm = haversine(lat, lon, plat, plon);
    if (distKm <= radiusKm) {
      list.push({
        名称: name,
        纬度: plat,
        经度: plon,
        距离: Math.round(distKm * 1000),
        步行分钟: Math.max(1, Math.round((distKm / 4.5) * 60)),
        高度: BUILDING_HEIGHT[name] || DEFAULT_HEIGHT,
      });
    }
  }
  // 半径内没有结果时，自动放宽到最近的几个点，保证"边走边推荐"始终有内容
  if (!list.length) {
    const all = [];
    for (const key of Object.keys(POI_COORDS)) {
      if (!key.startsWith(`${city}|`)) continue;
      const name = key.split("|")[1];
      if (seen.has(name)) continue;
      const [plat, plon] = POI_COORDS[key];
      const distKm = haversine(lat, lon, plat, plon);
      all.push({
        名称: name,
        纬度: plat,
        经度: plon,
        距离: Math.round(distKm * 1000),
        步行分钟: Math.max(1, Math.round((distKm / 4.5) * 60)),
        高度: BUILDING_HEIGHT[name] || DEFAULT_HEIGHT,
      });
    }
    all.sort((a, b) => a.距离 - b.距离);
    return all.slice(0, limit);
  }
  return list.sort((a, b) => a.距离 - b.距离).slice(0, limit);
}

/**
 * 按名称批量取真实坐标（行程打卡点上实景地图用）
 * 真实坐标库 → 城市中心派生兜底，保证每个打卡点都能落到地图上
 */
export function coordsFor(city, names = []) {
  const center = CITY_GEO[city]?.中心 || null;
  return names.map((name) => {
    const c = poiCoord(name, city) || center;
    return { 名称: name, 纬度: c ? c[0] : null, 经度: c ? c[1] : null };
  });
}

/** 两点间的真实步行耗时（分钟）与距离（米） */
export function walkInfo(lat1, lon1, lat2, lon2) {
  const distKm = haversine(lat1, lon1, lat2, lon2);
  return {
    距离: Math.round(distKm * 1000),
    步行分钟: Math.max(1, Math.round((distKm / 4.5) * 60)),
  };
}

