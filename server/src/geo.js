// 环线道路：以真实城市中心为圆心、按真实半径(km)生成的地面圆环
function ring(lat0, lon0, rKm, n = 30) {
  const pts = [];
  const dLat = rKm / 111.32;
  const dLon = rKm / (111.32 * Math.cos((lat0 * Math.PI) / 180));
  for (let i = 0; i <= n; i++) {
    const a = (i / n) * Math.PI * 2;
    pts.push([
      +(lat0 + dLat * Math.sin(a)).toFixed(5),
      +(lon0 + dLon * Math.cos(a)).toFixed(5),
    ]);
  }
  return pts;
}

