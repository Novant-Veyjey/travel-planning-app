/** 根据城市名获取当地特色（找不到返回通用） */
export function getCityFeature(city) {
  if (!city) city = "";
  // 别名映射：支持省级简称/全称
  const ALIASES = {
    "广东": "广州", "广东省": "广州",
    "重庆": "重庆", "重庆市": "重庆",
    "四川": "成都", "四川省": "成都",
    "西藏": "拉萨", "西藏自治区": "拉萨",
    "云南": "昆明", "云南省": "昆明",
    "贵州": "贵阳", "贵州省": "贵阳",
    "北京": "北京", "北京市": "北京",
    "上海": "上海", "上海市": "上海",
    "江西": "南昌", "江西省": "南昌",
    "福建": "福州", "福建省": "福州",
    "海南": "海口", "海南省": "海口",
    "黑龙江": "哈尔滨", "黑龙江省": "哈尔滨",
  };
  const key = ALIASES[city] || ALIASES[city.replace(/[省市自治区]+$/, "")] || city;
  const f = CITY_FEATURES[key] || CITY_FEATURES[city];
  if (f) {
    return {
      ...f,
      城市: key, // 归一化后的城市名（如"四川"→"成都"），供 POI/交通查询使用
      // 植被按城市配置 → 省份气候兜底 → 通用绿植
      植被: f.植被 || PROVINCE_FLORA[f.省份] || ["🌳", "🌿", "🌸", "🌾"],
      气候: f.气候 || PROVINCE_CLIMATE[f.省份] || "温和",
      图片键: PROVINCE_IMAGE_KEYS[f.省份] || "city-generic,city-generic,city-generic",
    };
  }
  return {
    省份: city || "未知",
    城市: city || "",
    气候: PROVINCE_CLIMATE[city] || "温和",
    植被: PROVINCE_FLORA[city] || ["🌳", "🌿", "🌸", "🌾"],
    特色建筑: [city || "当地地标"],
    地形: ["山水"],
    特色元素: ["当地美食"],
    建筑emoji: "🏙️",
    地形emoji: "🏞️",
    元素emoji: "🍜",
    图片键: "city-generic,city-generic,city-generic",
  };
}

/**
 * 由城市特色生成不重复的打卡点池（标志性景点 / 自然风光 / 美食打卡 + 派生景点）
 * 供 POI 接口与 mock 路线共用，保证"当地建筑"与打卡点都不为空
 * @returns {{名称:string, 类型:string, 特色:boolean}[]}
 */
export function buildCityPoiPool(city) {
  const base = city || "目的地";
  const feat = getCityFeature(base);
  const 建筑 = feat.特色建筑?.length ? feat.特色建筑 : [`${base}地标`];
  const 地形 = feat.地形?.length ? feat.地形 : [`${base}山水`];
  const 元素 = feat.特色元素?.length ? feat.特色元素 : [`${base}美食街`];

  const pool = [];
  const seen = new Set();
  const push = (名称, 类型, 特色 = true) => {
    if (!名称 || seen.has(名称)) return;
    seen.add(名称);
    pool.push({ 名称, 类型, 特色 });
  };
  建筑.forEach((n) => push(n, "标志性景点"));
  地形.forEach((n) => push(n, "自然风光"));
  元素.forEach((n) => push(n, "美食打卡"));
  // 派生景点：天数多时也能凑够且不重复
  ["人文博物馆", "老街", "夜市", "古城墙", "滨江公园", "艺术街区", "主题公园"].forEach((s, i) =>
    push(`${base}·${s}`, ["人文历史", "休闲街区", "夜游", "人文历史", "自然风光", "休闲街区", "标志性景点"][i], false)
  );
  return pool;
}

